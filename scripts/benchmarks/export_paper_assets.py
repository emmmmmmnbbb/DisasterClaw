#!/usr/bin/env python3
"""Export traceable LaTeX tables and figures from benchmark artifacts.

The generated files include a provenance manifest with source paths and
SHA-256 hashes so paper numbers are never transcribed by hand.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import shutil
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent.parent


def _load(path: Path) -> dict:
    return json.loads(path.read_text(encoding="utf-8"))


def _hash(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def _display_path(path: Path) -> str:
    try:
        return str(path.relative_to(REPO_ROOT))
    except ValueError:
        return str(path)


def _pct(value: float | None) -> str:
    return "--" if value is None else f"{100.0 * value:.1f}"


def _num(value: float | None, digits: int = 1) -> str:
    return "--" if value is None else f"{value:.{digits}f}"


def navigation_table(results: dict) -> str:
    rows = []
    for name in ("B0", "B1", "B2", "B3"):
        block = results["configs"].get(name)
        if not block:
            continue
        agg = block["agg"]
        rows.append(
            f"{name} & {_pct(agg.get('SR'))} & {_pct(agg.get('sem_SR'))} & "
            f"{_num(agg.get('NE_mean_m'))} & {_num(agg.get('sem_NE_mean_m'))} & "
            f"{_num(agg.get('SPL_mean'), 3)} & {_num(agg.get('steps_mean'), 2)} \\\\"
        )
    return "\n".join([
        "% Auto-generated by scripts/benchmarks/export_paper_assets.py",
        "\\begin{tabular}{lrrrrrr}",
        "\\toprule",
        "Method & SR (\\%) $\\uparrow$ & semSR (\\%) $\\uparrow$ & NE $\\downarrow$ & semNE $\\downarrow$ & SPL $\\uparrow$ & Steps $\\downarrow$ \\\\",
        "\\midrule",
        *rows,
        "\\bottomrule",
        "\\end{tabular}",
        "",
    ])


def reinspection_table(results: dict) -> str:
    short = {
        "E11_NONE": "None",
        "E11_RANDOM": "Random",
        "E11_FIXED": "Fixed",
        "E11_HEURISTIC": "Heuristic",
        "E11_ENTROPY": "Entropy",
        "E11_INFOGAIN": "InfoGain",
    }
    rows = []
    for name in short:
        block = results["configs"].get(name)
        if not block:
            continue
        agg = block["agg"]
        rows.append(
            f"{short[name]} & {_pct(agg.get('SR'))} & {_pct(agg.get('sem_SR'))} & "
            f"{_num(agg.get('NE_mean_m'))} & {_num(agg.get('SPL_mean'), 3)} & "
            f"{_num(agg.get('delta_u_mean'), 3)} \\\\"
        )
    return "\n".join([
        "% Auto-generated by scripts/benchmarks/export_paper_assets.py",
        "\\begin{tabular}{lrrrrr}",
        "\\toprule",
        "Policy & SR (\\%) $\\uparrow$ & semSR (\\%) $\\uparrow$ & NE $\\downarrow$ & SPL $\\uparrow$ & $\\Delta U$ \\\\",
        "\\midrule",
        *rows,
        "\\bottomrule",
        "\\end{tabular}",
        "",
    ])


def calibration_table(test: dict, holdout: dict) -> str:
    rows = []
    for split, data in (("Test", test), ("Holdout", holdout)):
        before = next(v for k, v in data["results"].items() if "uncalibrated" in k)
        after = next(v for k, v in data["results"].items() if "calibrated" in k and "uncalibrated" not in k)
        rows.extend([
            f"{split} & Uncalibrated & {_num(before['acc'], 3)} & {_num(before['ece'], 3)} & "
            f"{_num(before['brier'], 3)} & {_num(before['nll'], 3)} \\\\",
            f"{split} & Temperature scaled & {_num(after['acc'], 3)} & {_num(after['ece'], 3)} & "
            f"{_num(after['brier'], 3)} & {_num(after['nll'], 3)} \\\\",
        ])
    return "\n".join([
        "% Auto-generated by scripts/benchmarks/export_paper_assets.py",
        "\\begin{tabular}{llrrrr}",
        "\\toprule",
        "Split & Calibration & Acc. $\\uparrow$ & ECE $\\downarrow$ & Brier $\\downarrow$ & NLL $\\downarrow$ \\\\",
        "\\midrule",
        *rows,
        "\\bottomrule",
        "\\end{tabular}",
        "",
    ])


def reliability_plot(full: dict, out: Path) -> None:
    import matplotlib.pyplot as plt

    fig, ax = plt.subplots(figsize=(4.6, 3.6))
    for label, block in full["results"].items():
        xs, ys = [], []
        for bin_data in block.get("bins", []):
            if bin_data.get("conf") is not None and bin_data.get("acc") is not None:
                xs.append(bin_data["conf"])
                ys.append(bin_data["acc"])
        ax.plot(xs, ys, marker="o", linewidth=1.8, label=label.replace("calibrated", "temp. scaled"))
    ax.plot([0, 1], [0, 1], linestyle="--", color="black", linewidth=1, label="ideal")
    ax.set(xlabel="Confidence", ylabel="Empirical accuracy", xlim=(0, 1), ylim=(0, 1))
    ax.grid(alpha=0.2)
    ax.legend(fontsize=7)
    fig.tight_layout()
    fig.savefig(out, dpi=220)
    plt.close(fig)


