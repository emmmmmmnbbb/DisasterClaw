def yolo_metrics_table(metrics: dict) -> str:
    rows = []
    for split in ("val", "test", "holdout"):
        block = (metrics.get("results") or {}).get(split) or {}
        if not block:
            continue
        rows.append(
            f"{split} & {_num(block.get('precision'), 3)} & {_num(block.get('recall'), 3)} & "
            f"{_num(block.get('mAP50'), 3)} & {_num(block.get('mAP50_95'), 3)} \\\\"
        )
    return "\n".join([
        "% Auto-generated by scripts/benchmarks/export_paper_assets.py",
        "\\begin{tabular}{lrrrr}",
        "\\toprule",
        "Split & P $\\uparrow$ & R $\\uparrow$ & mAP@0.5 $\\uparrow$ & mAP@0.5:0.95 $\\uparrow$ \\\\",
        "\\midrule",
        *rows,
        "\\bottomrule",
        "\\end{tabular}",
        "",
    ])


def fusion_comparison_table(baseline: dict, diff: dict) -> str:
    def _pick(summary: dict, calibrated: bool) -> dict:
        for key, value in summary.get("results", {}).items():
            is_cal = "calibrated" in key and "uncalibrated" not in key
            if is_cal == calibrated:
                return value
        raise KeyError(summary)

    rows = []
    for split, base_sum, diff_sum in (
        ("Test", baseline["test"], diff["test"]),
        ("Holdout", baseline["holdout"], diff["holdout"]),
    ):
        b = _pick(base_sum, True)
        d = _pick(diff_sum, True)
        rows.append(
            f"{split} & Concatenation & {_num(b['acc'], 3)} & {_num(b['ece'], 3)} & "
            f"{_num(b['brier'], 3)} & {_num(b['nll'], 3)} \\\\"
        )
        rows.append(
            f"{split} & Difference attention & {_num(d['acc'], 3)} & {_num(d['ece'], 3)} & "
            f"{_num(d['brier'], 3)} & {_num(d['nll'], 3)} \\\\"
        )
    return "\n".join([
        "% Auto-generated by scripts/benchmarks/export_paper_assets.py",
        "\\begin{tabular}{llrrrr}",
        "\\toprule",
        "Split & Fusion & Acc. $\\uparrow$ & ECE $\\downarrow$ & Brier $\\downarrow$ & NLL $\\downarrow$ \\\\",
        "\\midrule",
        *rows,
        "\\bottomrule",
        "\\end{tabular}",
        "",
    ])


def event_split_table(manifest: dict) -> str:
    events = (manifest.get("split_audit") or {}).get("events") or {}
    rows = []
    for split in ("train", "val", "test", "holdout"):
        names = events.get(split) or []
        if split == "train" and len(names) > 4:
            joined = f"{len(names)} remaining events (appendix)"
        else:
            joined = ", ".join(names).replace("_", r"\_")
        rows.append(f"{split} & {len(names)} & {joined} \\\\")
    return "\n".join([
        "% Auto-generated by scripts/benchmarks/export_paper_assets.py",
        "\\begin{tabular}{lcp{5.2cm}}",
        "\\toprule",
        "Split & \\#Events & Event names \\\\",
        "\\midrule",
        *rows,
        "\\bottomrule",
        "\\end{tabular}",
        "",
    ])


def copy_qualitative_cases(out: Path) -> list[str]:
    cases_dir = REPO_ROOT / "runs/benchmarks/e9_figures/cases"
    copied = []
    if not cases_dir.is_dir():
        return copied
    target = out / "cases"
    target.mkdir(parents=True, exist_ok=True)
    for name in (
        "case_04_E1-sem成功_semNE=12.53m.png",
        "case_06_E1-失败_NE=1304.66m_easy.png",
        "case_01_E4-seed成功_NE=0.0m.png",
    ):
        source = cases_dir / name
        if source.exists():
            shutil.copy2(source, target / name)
            copied.append(name)
    return copied


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument(
        "--navigation",
        default=str(REPO_ROOT / "runs/benchmarks/20260623_202108_e1full/results.json"),
    )
    ap.add_argument(
        "--reinspection",
        default=str(REPO_ROOT / "runs/benchmarks/paper_strict_v1/e11/results.json"),
    )
    ap.add_argument(
        "--calibration-dir",
        default=str(
            REPO_ROOT / "runs/benchmarks/paper_strict_v1/calibration_baseline"
        ),
    )
    ap.add_argument(
        "--diff-calibration-dir",
        default=str(
            REPO_ROOT
            / "runs/benchmarks/paper_strict_v1/calibration_diff_attention"
        ),
    )
    ap.add_argument(
        "--yolo-metrics",
        default=str(REPO_ROOT / "runs/benchmarks/paper_strict_v1/yolo_metrics.json"),
    )
    ap.add_argument("--out", default=str(REPO_ROOT / "paper/generated"))
    ap.add_argument(
        "--strict-yolo-manifest",
        default="/home/lc/datasets/xbd_yolo_strict_v1/manifest.json",
    )
    ap.add_argument(
        "--strict-change-manifest",
        default="/home/lc/datasets/xbd_change_strict_v1/manifest.json",
    )
    ap.add_argument(
        "--reinspection-testset",
        default=str(
            REPO_ROOT / "backend/data/benchmarks/vln_recheck_testset.json"
        ),
    )
    args = ap.parse_args()

    navigation_path = Path(args.navigation)
    reinspection_path = Path(args.reinspection)
    calibration_dir = Path(args.calibration_dir)
    diff_calibration_dir = Path(args.diff_calibration_dir)
    yolo_metrics_path = Path(args.yolo_metrics)
    test_path = calibration_dir / "test_summary.json"
    holdout_path = calibration_dir / "holdout_summary.json"
    full_path = calibration_dir / "test_full.json"
    diff_test_path = diff_calibration_dir / "test_summary.json"
    diff_holdout_path = diff_calibration_dir / "holdout_summary.json"
    strict_manifests = [
        Path(args.strict_yolo_manifest),
        Path(args.strict_change_manifest),
    ]
    reinspection_testset = Path(args.reinspection_testset)
    sources = [
        navigation_path,
        reinspection_path,
        test_path,
        holdout_path,
        full_path,
        diff_test_path,
        diff_holdout_path,
        yolo_metrics_path,
        *strict_manifests,
        reinspection_testset,
    ]
    for source in sources:
        if not source.exists():
            raise FileNotFoundError(source)

    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    (out / "navigation_table.tex").write_text(
        navigation_table(_load(navigation_path)), encoding="utf-8"
    )
    (out / "reinspection_table.tex").write_text(
        reinspection_table(_load(reinspection_path)), encoding="utf-8"
    )
    (out / "calibration_table.tex").write_text(
        calibration_table(_load(test_path), _load(holdout_path)), encoding="utf-8"
    )
    (out / "fusion_comparison_table.tex").write_text(
        fusion_comparison_table(
            {"test": _load(test_path), "holdout": _load(holdout_path)},
            {"test": _load(diff_test_path), "holdout": _load(diff_holdout_path)},
        ),
        encoding="utf-8",
    )
    (out / "yolo_metrics_table.tex").write_text(
        yolo_metrics_table(_load(yolo_metrics_path)), encoding="utf-8"
    )
    reliability_plot(_load(full_path), out / "calibration_reliability.pdf")
    system_overview_plot(out / "system_overview.pdf")
    recheck_state_plot(out / "recheck_state.pdf")
    (out / "event_split_table.tex").write_text(
        event_split_table(_load(strict_manifests[1])), encoding="utf-8"
    )
    for source, name in zip(
        strict_manifests,
        ("strict_yolo_manifest.json", "strict_change_manifest.json"),
    ):
        shutil.copy2(source, out / name)
    shutil.copy2(reinspection_testset, out / "vln_recheck_testset.json")
    shutil.copy2(yolo_metrics_path, out / "yolo_metrics.json")
    copied_cases = copy_qualitative_cases(out)
    review_src = REPO_ROOT / "runs/benchmarks/vln_recheck_review"
    review_dst = out / "review_sheets"
    review_dst.mkdir(parents=True, exist_ok=True)
    copied_reviews = []
    for name in ("review_01.jpg", "review_02.jpg", "review_03.jpg"):
        source = review_src / name
        if source.exists():
            shutil.copy2(source, review_dst / name)
            copied_reviews.append(name)

    legacy_figures = REPO_ROOT / "runs/benchmarks/e9_figures"
    for name in ("08_pipeline.png", "01_e1_ablation.png"):
        source = legacy_figures / name
        if source.exists():
            shutil.copy2(source, out / name)

    provenance = {
        "generator": "scripts/benchmarks/export_paper_assets.py",
        "sources": [
            {
                "path": _display_path(path),
                "sha256": _hash(path),
            }
            for path in sources
        ],
        "qualitative_cases": copied_cases,
        "review_sheets": copied_reviews,
        "warning": (
            "Navigation results default to the historical repeat=1 run. "
            "Replace --navigation with the strict repeat>=3 run before submission."
        ),
    }
    (out / "provenance.json").write_text(
        json.dumps(provenance, indent=2), encoding="utf-8"
    )
    print(f"paper assets -> {out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
